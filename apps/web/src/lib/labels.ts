import type { Insights, Story } from "./types.ts";

export function transcriptLabel(story: Pick<Story, "transcript" | "originalTranscript" | "transcriptSource" | "transcriptModel">): string {
  switch (story.transcriptSource) {
    case "whisper": {
      const model = story.transcriptModel ? ` (${story.transcriptModel})` : "";
      return story.transcript === story.originalTranscript
        ? `Transcribed by Whisper${model}.`
        : `Whisper transcript${model}, edited by you. The original is kept.`;
    }
    case "manual":
      return "Typed by you.";
    case "demo":
      return "Synthetic demonstration transcript. Not from Whisper.";
    case "none":
      return "No transcript yet.";
    default: {
      const neverSource: never = story.transcriptSource;
      return neverSource;
    }
  }
}

export function insightLabel(insights: Insights): string {
  if (insights.source === "demo") {
    return insights.edited
      ? "Synthetic demonstration, edited by you. Not produced by Gemma."
      : "Synthetic demonstration. These insights were not produced by Gemma.";
  }
  const model = insights.model ?? "Gemma";
  return insights.edited
    ? `AI-generated by ${model} through Ollama, then edited by you.`
    : `AI-generated by ${model} through Ollama. Not edited.`;
}
